export function t(key, lang = "en") {
  const keys = key.split(".");
  let val = translations[lang] || translations.en;
  for (const k of keys) {
    if (val && typeof val === "object" && k in val) {
      val = val[k];
    } else {
      val = key;
      break;
    }
  }
  return typeof val === "string" ? val : key;
}

export default translations;
